def all_text(obj):
    out = []

    def walk(o):
        if isinstance(o, str):
            out.append(o)
        elif isinstance(o, list):
            for x in o:
                walk(x)
        elif isinstance(o, dict):
            for v in o.values():
                walk(v)

    walk(obj)
    return out


def validate_admin_screens(doc, wireframe_ids, vendor_names):
    p = []
    screens = doc.get("screens", [])
    ids = [s.get("id") for s in screens]
    expected_ids = ["M%02d" % n for n in range(2, 15)]
    if sorted(x for x in ids if x) != sorted(expected_ids) or len(ids) != len(set(ids)):
        p.append("screen ids are not exactly M02 to M14, one each: got %s" % ids)

    admin_ids = set(ids)
    for s in screens:
        sid = s.get("id", "?")
        for key in ("id", "sec", "title", "tier", "frame", "template", "path", "purpose", "ui", "events",
                    "compliance", "freeze", "v02", "spec", "seat", "role", "built", "writes", "zoho_instead"):
            if key not in s:
                p.append("%s: missing %s" % (sid, key))
        if s.get("template") not in TEMPLATES_F:
            p.append("%s: template %r not in the 21 appendix-F templates" % (sid, s.get("template")))
        if s.get("path") not in ("both", "aa", "manual"):
            p.append("%s: path %r" % (sid, s.get("path")))
        events = s.get("events") or []
        if (sid + "_view") not in events:
            p.append("%s: events missing %s_view" % (sid, sid))
        c = s.get("compliance") or {}
        if not isinstance(c.get("review"), bool) or not c.get("reasons"):
            p.append("%s: compliance flag incomplete" % sid)
        f = s.get("freeze") or {}
        if f.get("status") != "open" or not f.get("reason"):
            p.append("%s: freeze is not open with a reason" % sid)
        v = s.get("v02") or {}
        if not v.get("causes"):
            p.append("%s: v02 has no causes" % sid)
        spec = s.get("spec") or {}
        for key in ("fields", "logic", "branches", "states", "dev"):
            if key not in spec:
                p.append("%s: spec missing %s" % (sid, key))

        role = s.get("role") or {}
        for k, v2 in role.items():
            if k not in ROLES:
                p.append("%s: role key %r is not one of the eight roles" % (sid, k))
            if v2 not in ROLE_VALUES:
                p.append("%s: role %r value %r is not act, read or 'read, own people'" % (sid, k, v2))
        writes = s.get("writes") or []
        write_events = set()
        for w in writes:
            if not w.get("action") or not w.get("event") or not w.get("roles"):
                p.append("%s: writes entry missing action, event or roles: %r" % (sid, w))
                continue
            write_events.add(w["event"])
            for r in w["roles"]:
                if r not in ROLES:
                    p.append("%s: writes role %r is not one of the eight roles" % (sid, r))
        missing = write_events - set(events)
        if missing:
            p.append("%s: writes events not listed in events: %s" % (sid, sorted(missing)))

        for label, target in spec.get("branches", []):
            if target not in admin_ids and target not in wireframe_ids:
                p.append("%s: branch %r -> %s is neither an admin screen nor a wireframes screen" % (sid, label, target))

    texts = all_text(doc)
    for txt in texts:
        for name in validate_v02.NAMES_UI:
            if validate_v02.word_hit(txt, name):
                p.append("data/admin_screens.json: team name %s in text: %r" % (name, txt[:70]))
        for vendor in vendor_names:
            if vendor and vendor in txt:
                p.append("data/admin_screens.json: vendor name %s in text: %r" % (vendor, txt[:70]))
    for txt in texts:
        for ch in txt:
            if ord(ch) > 126:
                p.append("data/admin_screens.json: non-ASCII in %r" % txt[:60])
                break
    return p


