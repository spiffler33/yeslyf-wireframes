def anchor_display(iso):
    months = ["Jan", "Feb", "Mar", "Apr", "May", "Jun", "Jul", "Aug", "Sep", "Oct", "Nov", "Dec"]
    d = iso[:10].split("-")
    if len(d) != 3:
        return iso
    y, m, day = d
    return "%d %s %s" % (int(day), months[int(m) - 1], y)


