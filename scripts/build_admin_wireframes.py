# ---------------------------------------------------------------- small helpers

def mask_phone(p):
    """"9000052984" -> "+91 9xxxx xx984": "+91 ", the first digit, "xxxx xx", the last three digits. Plain slicing."""
    return "+91 " + p[0] + "xxxx xx" + p[-3:]


def table_count(d):
    """Total rows for a dict-of-list-of-rows table, or the key count for a dict-of-one-row-per-person table."""
    total = 0
    for v in d.values():
        total += len(v) if isinstance(v, list) else 1
    return total


def read_anchor(run_dir):
    """The run's anchor, from the fixed first line of report.md: "Anchor <iso> (every date...". Plain prefix
    slicing (report.md is generated by scripts/seed_gen.py in this same repo, a closed machine format, not text
    parsed by a pattern rule); seed/config.json's own "anchor" block only carries the default rule ("run date"),
    not the concrete value used for this run, so report.md is the only place the actual anchor is recorded."""
    with open(os.path.join(run_dir, "report.md")) as fh:
        head = fh.read(600)
    for line in head.split("\n"):
        if line.startswith("Anchor "):
            return line[len("Anchor "):].split(" ", 1)[0]
    raise SystemExit("no 'Anchor ' line found in %s/report.md" % run_dir)


def load_table(run_dir, name):
    with open(os.path.join(run_dir, name + ".json")) as fh:
        return json.load(fh)


