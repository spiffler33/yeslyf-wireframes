def build_people(raw_people):
    """people.json: array sorted by person_id, without pan/dob/legal_name, phone masked."""
    out = []
    for pid in sorted(raw_people):
        rec = {k: v for k, v in raw_people[pid].items() if k not in EXCLUDED_PEOPLE_FIELDS}
        if rec.get("phone"):
            rec["phone"] = mask_phone(rec["phone"])
        out.append(rec)
    return out


def build_sip(financial_records):
    """{person_id: {value, value_kind, source, precision}} of each person's current_sip record (the M13 SIP book
    reads the AA-detected and typed SIPs without loading every person chunk)."""
    out = {}
    for pid, rows in financial_records.items():
        for row in rows:
            if row.get("field") == "current_sip":
                out[pid] = {"value": row.get("value"), "value_kind": row.get("value_kind"), "source": row.get("source"),
                            "precision": row.get("precision")}
    return out


def build_assets(financial_records, investable_fields):
    """{person_id: {field: number}} for every person with a financial record, over the investable field list."""
    out = {}
    for pid, rows in financial_records.items():
        assets = {}
        for row in rows:
            f = row.get("field")
            if f in investable_fields and row.get("value_kind") in ("exact", "band") and row.get("value") is not None:
                assets[f] = row["value"]
        out[pid] = assets
    return out


def stream_events(run_dir, wanted_types):
    """One pass over events.jsonl: per-person compact rows for the chunk files (signed_up.props.phone masked),
    plus the raw rows of the event types the audit log needs (so it never re-reads the file)."""
    by_person = {}
    by_type = {t: [] for t in wanted_types}
    path = os.path.join(run_dir, "events.jsonl")
    with open(path) as fh:
        for line in fh:
            line = line.strip()
            if not line:
                continue
            e = json.loads(line)
            props = e.get("props") or {}
            if e["event"] == "signed_up" and props.get("phone"):
                props = dict(props)
                props["phone"] = mask_phone(props["phone"])
            by_person.setdefault(e["person_id"], []).append([e["at"], e["event"], e.get("screen_id"), props])
            if e["event"] in by_type:
                by_type[e["event"]].append(e)
    return by_person, by_type


AUDIT_WHO_SYSTEM = "system"
AUDIT_WHO_USER = "user"


def build_audit(tables, staff_by_id, by_type):
    """The M11 log: one row {at, person_id, record, action, who, detail} per regulated-record change found in the
    seed. Sourced from plan_versions/rpq/payments/aa_consents/calls/tasks/ops_queue rows and from the events of
    esign_done, plan_updated, update_accepted, payment_failed, aa_connected, aa_failed, cancelled and
    sharpen_saved. who is "user", "system" or a staff display name (call completions and resolved ops-queue items
    are attributed to the staff member on the row)."""
    rows = []

    def staff_name(sid):
        rec = staff_by_id.get(sid)
        return rec["name"] if rec else (sid or "system")

    for e in by_type.get("esign_done", []):
        rows.append({"at": e["at"], "person_id": e["person_id"], "record": "agreement", "action": "signed",
                     "who": AUDIT_WHO_USER,
                     "detail": {"agreement_version": e["props"].get("agreement_version"),
                                "esign_ref": e["props"].get("esign_ref")}})

    for pid, rec in tables["rpq"].items():
        if rec.get("taken_at"):
            rows.append({"at": rec["taken_at"], "person_id": pid, "record": "risk_profile", "action": "taken",
                         "who": AUDIT_WHO_USER, "detail": {"risk_band": rec.get("risk_band")}})

    for pid, versions in tables["plan_versions"].items():
        for v in versions:
            if v.get("built_at"):
                rows.append({"at": v["built_at"], "person_id": pid, "record": "plan", "action": "built",
                             "who": AUDIT_WHO_SYSTEM,
                             "detail": {"plan_version": v.get("plan_version"),
                                        "assumptions_version": v.get("assumptions_version"),
                                        "instrument_set_version": v.get("instrument_set_version")}})
    for e in by_type.get("plan_updated", []):
        rows.append({"at": e["at"], "person_id": e["person_id"], "record": "plan", "action": "updated",
                     "who": AUDIT_WHO_SYSTEM,
                     "detail": {"from_version": e["props"].get("from_version"), "to_version": e["props"].get("to_version"),
                                "reason": e["props"].get("reason")}})
    for e in by_type.get("update_accepted", []):
        rows.append({"at": e["at"], "person_id": e["person_id"], "record": "plan", "action": "accepted",
                     "who": AUDIT_WHO_USER, "detail": {"to_version": e["props"].get("to_version")}})

    for pid, payments in tables["payments"].items():
        for p in payments:
            status = p.get("status")
            if status in ("captured", "refunded") and p.get("paid_at"):
                rows.append({"at": p["paid_at"], "person_id": pid, "record": "payment",
                             "action": status, "who": AUDIT_WHO_USER if status == "captured" else AUDIT_WHO_SYSTEM,
                             "detail": {"invoice_no": p.get("invoice_no"), "amount": p.get("amount")}})
    for e in by_type.get("payment_failed", []):
        rows.append({"at": e["at"], "person_id": e["person_id"], "record": "payment", "action": "failed",
                     "who": AUDIT_WHO_SYSTEM, "detail": {"grace_until": e["props"].get("grace_until")}})
    for e in by_type.get("cancelled", []):
        if e["props"].get("refund_requested"):
            rows.append({"at": e["at"], "person_id": e["person_id"], "record": "payment", "action": "refund_requested",
                         "who": AUDIT_WHO_USER, "detail": {"reason": e["props"].get("reason")}})

    for e in by_type.get("aa_connected", []):
        rows.append({"at": e["at"], "person_id": e["person_id"], "record": "aa_consent", "action": "connected",
                     "who": AUDIT_WHO_USER,
                     "detail": {"institutions_ok": e["props"].get("institutions_ok"),
                                "institutions_failed": e["props"].get("institutions_failed")}})
    for e in by_type.get("aa_failed", []):
        rows.append({"at": e["at"], "person_id": e["person_id"], "record": "aa_consent", "action": "failed",
                     "who": AUDIT_WHO_SYSTEM,
                     "detail": {"institutions_ok": e["props"].get("institutions_ok"),
                                "institutions_failed": e["props"].get("institutions_failed")}})
    for pid, consents in tables["aa_consents"].items():
        for c in consents:
            if c.get("renewed_at"):
                rows.append({"at": c["renewed_at"], "person_id": pid, "record": "aa_consent", "action": "renewed",
                             "who": AUDIT_WHO_USER, "detail": {"consent_expiry": c.get("consent_expiry")}})
            if c.get("status") == "expired" and c.get("consent_expiry"):
                rows.append({"at": c["consent_expiry"], "person_id": pid, "record": "aa_consent", "action": "expired",
                             "who": AUDIT_WHO_SYSTEM, "detail": {}})

    for pid, calls in tables["calls"].items():
        for c in calls:
            if c.get("status") == "completed" and c.get("input_changes") and c.get("slot"):
                rows.append({"at": c["slot"], "person_id": pid, "record": "call", "action": "completed",
                             "who": staff_name(c.get("adviser_id")), "detail": {"input_changes": c["input_changes"]}})

    for pid, tasks in tables["tasks"].items():
        for t in tasks:
            if t.get("state_id") == "S25":
                fields = t.get("fields") or {}
                at = fields.get("requested_at") or t.get("created_at")
                if at:
                    rows.append({"at": at, "person_id": pid, "record": "deletion", "action": "requested",
                                 "who": AUDIT_WHO_USER, "detail": {"records_retained": fields.get("records_retained")}})

    for pid, items in tables["ops_queue"].items():
        for it in items:
            if it.get("status") == "resolved" and it.get("resolved_at"):
                rows.append({"at": it["resolved_at"], "person_id": pid, "record": "ops_queue", "action": "resolved",
                             "who": staff_name(it.get("owner")), "detail": {"type": it.get("type"), "detail": it.get("detail")}})

    for e in by_type.get("sharpen_saved", []):
        rows.append({"at": e["at"], "person_id": e["person_id"], "record": "financial_record", "action": "sharpened",
                     "who": AUDIT_WHO_USER, "detail": {"field": e["props"].get("field")}})

    rows.sort(key=lambda r: (r["at"], r["person_id"], r["record"], r["action"]))
    counts = {}
    for r in rows:
        counts[r["record"]] = counts.get(r["record"], 0) + 1
    return rows, counts


