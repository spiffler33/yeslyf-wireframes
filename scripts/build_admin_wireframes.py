def build_bundle(run, investable_fields):
    run_dir = os.path.join(SEED_DATA, "run-" + run)
    out_dir = os.path.join(DOCS, "seed", "run-" + run, "admin")
    os.makedirs(os.path.join(out_dir, "person"), exist_ok=True)

    raw_people = load_table(run_dir, "people")
    raw_staff = load_table(run_dir, "staff")
    app_config = load_table(run_dir, "config")

    tables_src = {name: load_table(run_dir, name) for name in ALL_SOURCE_TABLES}
    audit_event_types = ["esign_done", "plan_updated", "update_accepted", "payment_failed", "aa_connected",
                          "aa_failed", "cancelled", "sharpen_saved"]
    events_by_person, events_by_type = stream_events(run_dir, audit_event_types)

    people_ids_sorted = sorted(raw_people)
    people_bundle = build_people(raw_people)
    staff_bundle = [raw_staff[k] for k in sorted(raw_staff)]
    staff_by_id = raw_staff

    assets = build_assets(tables_src["financial_records"], investable_fields)
    audit_rows, audit_counts = build_audit(tables_src, staff_by_id, events_by_type)

    tables_json = {"staff": staff_bundle, "config": app_config, "assets": assets, "audit": audit_rows,
                   "sip": build_sip(tables_src["financial_records"])}
    for name in PASSTHROUGH_TABLES:
        tables_json[name] = tables_src[name]

    # person chunks, 100 per file, in person_id order
    n_chunks = (len(people_ids_sorted) + CHUNK_SIZE - 1) // CHUNK_SIZE if people_ids_sorted else 0
    chunk_files = {}
    for idx in range(n_chunks):
        chunk_ids = people_ids_sorted[idx * CHUNK_SIZE:(idx + 1) * CHUNK_SIZE]
        chunk = {}
        for pid in chunk_ids:
            entry = {}
            for name in CHUNK_TABLES:
                entry[name] = tables_src[name].get(pid, [] if name not in ("households", "reveal", "covers", "rpq", "state_flags") else {})
            entry["events"] = events_by_person.get(pid, [])
            chunk[pid] = entry
        chunk_files["%04d" % idx] = chunk

    anchor = read_anchor(run_dir)
    counts = {"people": len(people_bundle), "staff": len(staff_bundle), "assets": len(assets),
              "audit": len(audit_rows)}
    for name in ALL_SOURCE_TABLES:
        counts[name] = table_count(tables_src[name])
    meta = {"run": run, "anchor": anchor, "seed": 20260922, "counts": counts, "chunk_size": CHUNK_SIZE,
            "chunks": n_chunks, "excluded": list(EXCLUDED_PEOPLE_FIELDS), "masked": list(MASKED_FIELDS)}

    files = {
        "meta.json": meta,
        "people.json": people_bundle,
        "tables.json": tables_json,
        "integration_events.json": tables_src["integration_events"],
    }
    for name, chunk in chunk_files.items():
        files["person/%s.json" % name] = chunk

    written = {}
    for rel, obj in files.items():
        text = json.dumps(obj, sort_keys=True, separators=(",", ":"), ensure_ascii=True)
        path = os.path.join(out_dir, rel)
        with open(path, "w") as fh:
            fh.write(text)
        written[rel] = text

    # minimisation: no PAN, no raw phone (every person, not just paid) anywhere in any written file; ASCII everywhere.
    # Source scan (both runs) found exactly two places carrying a raw phone: people.<id>.phone, and the
    # signed_up event's props.phone; both are masked above before any file is written. This scan is the safety net.
    pans = {v["pan"] for v in raw_people.values() if v.get("pan")}
    phones = {v["phone"] for v in raw_people.values() if v.get("phone")}
    leaks = []
    for rel, text in written.items():
        for pan in pans:
            if pan in text:
                leaks.append("%s: PAN %s" % (rel, pan))
        for phone in phones:
            if phone in text:
                leaks.append("%s: raw phone %s" % (rel, phone))
        for ch in text:
            if ord(ch) > 126:
                leaks.append("%s: non-ASCII character" % rel)
                break
    if leaks:
        raise SystemExit("admin bundle minimisation scan failed:\n" + "\n".join(leaks[:40]))

    return {
        "run": run, "anchor": anchor, "counts": counts, "audit_counts": audit_counts,
        "bytes": {rel: len(text) for rel, text in written.items()},
    }


